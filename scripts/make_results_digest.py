"""Assemble docs/RESULTS_AUTO.md — a single always-current Markdown digest of every
result the project has produced: all tables inline + a gallery index of every figure +
the raw per-(model,split) metric grid. Machine-generated; regenerated by cycle.py each
time new results land, so the user always has the complete data in one .md to write from.

    .venv/Scripts/python.exe -m scripts.make_results_digest [--out docs/RESULTS_AUTO.md]

Curated narrative + interpretation live in docs/RESULTS.md (hand-maintained); this file is
the exhaustive machine dump.
"""
from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

from src.viz import data as vdata
from src.viz import style

ROOT = Path(__file__).resolve().parents[1]
SPLIT_ORDER = ["full", "scarce", "reynolds", "aoa", "shape5", "combined"]
FIG_CAPTIONS = {
    "fig01": "Protocol schematic (three families + shared harness)",
    "fig02": "cp profiles, in-distribution + OOD",
    "fig03": "Surface pressure fields (pred / truth / error)",
    "fig04": "Field error vs distribution shift (centerpiece)",
    "fig05": "Force self-consistency scatter (C_D int vs head)",
    "fig06": "Reliability diagram (empirical vs nominal coverage)",
    "fig07": "Coverage vs distribution shift",
    "fig08": "Interval width, in-distribution vs OOD",
    "fig09": "Data-efficiency curves (rel-L2 vs train size)",
    "fig10": "Symmetry residual per model",
    "fig11_active_pool": "Active-learning pool scoring (selection)",
    "fig11_active_verify": "Surrogate-vs-Fluent by arm (accepted set)",
    "fig12": "Cost vs accuracy (Pareto)",
}
METRIC_GRIDS = [
    ("Field pressure rel-L2 (lower=better)", ["field", "p_rel_l2"], "{:.4f}"),
    ("Field wall-shear rel-L2", ["field", "tau_rel_l2"], "{:.4f}"),
    ("C_D head MAE", ["coef", "cd_head_mae"], "{:.5f}"),
    ("C_D ranking Spearman (higher=better)", ["coef", "cd_head_spearman"], "{:.3f}"),
    ("Force self-consistency FSC_cd (lower=better)", ["consistency", "fsc_cd"], "{:.4f}"),
    ("Symmetry residual", ["consistency", "sym_residual"], "{:.2f}"),
]
MODELS = ["transolver", "sdf_fno", "gnn"]


def _dig(d, path):
    for k in path:
        if not isinstance(d, dict):
            return None
        d = d.get(k)
    return d


def _metric_table(results_dir: Path, path, fmt) -> str:
    header = "| model | " + " | ".join(SPLIT_ORDER) + " |"
    sep = "| --- |" + " --- |" * len(SPLIT_ORDER)
    rows = [header, sep]
    for mdl in MODELS:
        cells = [style.model_label(mdl) if hasattr(style, "model_label") else mdl]
        for sp in SPLIT_ORDER:
            mp = results_dir / f"{mdl}_{sp}_s0" / "metrics.json"
            if mp.exists():
                v = _dig(json.loads(mp.read_text()), path)
                cells.append(fmt.format(v) if isinstance(v, (int, float)) else "NA")
            else:
                cells.append("--")
        rows.append("| " + " | ".join(cells) + " |")
    return "\n".join(rows)


def _inline_md_table(p: Path) -> str:
    return p.read_text(encoding="utf-8").strip() if p.exists() else "_(not generated yet)_"


def build(results_dir: Path, tables_dir: Path, figs_dir: Path) -> str:
    out = []
    out.append("# RESULTS_AUTO — machine-generated results digest\n")
    out.append(f"Auto-generated {date.today().isoformat()} by `scripts/make_results_digest.py` "
               "(regenerated automatically as new runs land). For interpretation see "
               "[RESULTS.md](RESULTS.md); for concepts see [OVERVIEW.md](OVERVIEW.md).\n")

    # run inventory
    runs = sorted(p.name for p in results_dir.glob("*_s*") if (p / "metrics.json").exists())
    out.append(f"## Run inventory ({len(runs)} runs with metrics)\n")
    out.append("```\n" + "\n".join(runs) + "\n```\n")

    # per-metric grids (seed-0)
    out.append("## Core metric grids (seed 0, 3 models x 6 splits)\n")
    for title, path, fmt in METRIC_GRIDS:
        out.append(f"### {title}\n")
        out.append(_metric_table(results_dir, path, fmt) + "\n")

    # generated tables inline
    out.append("## Generated tables\n")
    for slug, title in [("tab1_indist", "Table 1 — in-distribution accuracy/consistency/cost"),
                        ("tab2_ood", "Table 2 — OOD field error by split"),
                        ("tab3_calibration", "Table 3 — calibration coverage/width"),
                        ("tab4_ablation", "Table 4 — ablations"),
                        ("tab5_selected_cases", "Table 5 — active-learning selected cases")]:
        p = tables_dir / f"{slug}.md"
        if p.exists():
            out.append(f"### {title}\n")
            out.append(_inline_md_table(p) + "\n")

    # figure gallery
    out.append("## Figure gallery\n")
    out.append("All figures are in `paper/figures/` (PDF + PNG). Present now:\n")
    for key, cap in FIG_CAPTIONS.items():
        pngs = list(figs_dir.glob(f"{key}*.png"))
        if pngs:
            rel = pngs[0].relative_to(ROOT).as_posix()
            out.append(f"### {key}: {cap}\n")
            out.append(f"![{cap}](../{rel})\n")
        else:
            out.append(f"- {key}: {cap} — _pending_\n")
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default="docs/RESULTS_AUTO.md")
    ap.add_argument("--results", default="results")
    ap.add_argument("--tables", default="paper/tables")
    ap.add_argument("--figs", default="paper/figures")
    args = ap.parse_args(argv)
    txt = build(ROOT / args.results, ROOT / args.tables, ROOT / args.figs)
    (ROOT / args.out).write_text(txt, encoding="utf-8")
    print(f"wrote {args.out} ({len(txt)} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
